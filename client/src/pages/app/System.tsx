import PageHeading from '../../components/ui/PageHeading'
import DataState from '../../components/ui/DataState'
import RefreshButton from '../../components/ui/RefreshButton'
import { useSystemStatus } from '../../hooks/useValeriaData'
import { useSensorReadingEvents } from '../../realtime/useSensorReadingEvents'

const currentFlow = [
  [
    ['Simulated sensors', 'Stateful, time-aware environmental readings'],
    ['MQTT / direct ingestion', 'Authenticated broker path or direct service call'],
    ['Express backend', 'Validates readings and greenhouse ownership'],
    ['Prisma', 'Typed database access and transactions'],
  ],
  [
    ['PostgreSQL', 'Persistent source of truth'],
    ['Alert + irrigation intelligence', 'Threshold events and moisture recommendations'],
    ['Socket.IO + REST', 'Live updates and initial / historical data'],
    ['React website', 'Dashboard, monitor, analytics, and controls'],
  ],
]

function ArchitectureFlow({ steps, label, startAt = 0 }: { steps: string[][]; label: string; startAt?: number }) {
  return (
    <div className="architecture-flow" aria-label={label}>
      {steps.map(([title, detail], index) => (
        <div className="flow-step-wrap" key={title}>
          <div className="flow-step">
            <span className="flow-index">0{startAt + index + 1}</span>
            <strong>{title}</strong>
            <small>{detail}</small>
          </div>
          {index < steps.length - 1 && <span className="flow-arrow" aria-hidden="true">→</span>}
        </div>
      ))}
    </div>
  )
}

export default function System() {
  const statusData = useSystemStatus()
  const realtime = useSensorReadingEvents(statusData.refresh)
  const status = statusData.data
  const connections = status ? [
    ['Overall', status.overallStatus],
    ['Sensor sync', status.sensorSync],
    ['MQTT transport', status.mqttStatus],
    ['Live updates', realtime.connectionStatus],
    ['Database', status.databaseStatus],
  ] as const : []

  return (
    <div className="page-content">
      <PageHeading
        eyebrow="HOW VALERIA FITS TOGETHER"
        title="System architecture"
        description="A transparent view of how simulated greenhouse readings become stored data and useful insight."
        action={<span className="architecture-tag">{status?.overallStatus === 'online' ? 'SERVICE STATUS · ONLINE' : 'SERVICE STATUS · CHECKING'}</span>}
      />
      {statusData.loading || statusData.error ? (
        <DataState loading={statusData.loading} error={statusData.error} onRetry={() => void statusData.refresh()} />
      ) : status && (
        <section className="surface-card system-connection-panel" aria-label="Service connection status">
          <div className="section-head">
            <div><span className="panel-kicker">CURRENT CONNECTIONS</span><h2>Service status</h2></div>
            <div className="data-action-group"><span className="table-note">Last sync {status.lastSync}</span><RefreshButton onClick={() => void statusData.refresh()} /></div>
          </div>
          <div className="system-connection-list">
            {connections.map(([name, state]) => (
              <div className="system-connection-row" key={name}>
                <span>{name}</span>
                <strong className={`connection-state connection-${state}`}>{state}</strong>
              </div>
            ))}
          </div>
        </section>
      )}
      <section className="surface-card architecture-panel">
        <div className="architecture-heading">
          <span className="panel-kicker">CURRENT DATA PATH · SIMULATED SENSOR DATA</span>
          <h2>From simulated readings to greenhouse insight</h2>
          <p>Current values are generated by the software simulator; physical sensors are not connected. The backend supports both direct ingestion and an authenticated MQTT route.</p>
        </div>
        <ArchitectureFlow steps={currentFlow[0]} label="Current data path, part one: simulated sensors through transport and backend to Prisma" />
        <ArchitectureFlow steps={currentFlow[1]} startAt={4} label="Current data path, part two: PostgreSQL through intelligence and APIs to the React website" />
        <p className="architecture-note"><span>Source of truth</span>Readings, alerts, and irrigation recommendations persist in PostgreSQL. REST provides initial and historical data; authenticated Socket.IO delivers authorized updates after persistence. Irrigation remains a software recommendation only.</p>
      </section>
      <section className="surface-card architecture-panel future-hardware-panel">
        <div className="architecture-heading">
          <span className="panel-kicker">FUTURE INTEGRATION · NOT CONNECTED</span>
          <h2>Physical sensor architecture</h2>
          <p>ESP32 / Arduino → physical sensors → MQTT → VALERIA backend → PostgreSQL → website</p>
          <p>This is a future integration path, not a description of hardware currently operating in this project.</p>
        </div>
      </section>
    </div>
  )
}
